    FOREIGN KEY (inference_item_id, student_id)
    REFERENCES acad_mentorship_inference_items(id, student_id),
  CONSTRAINT ati_requests_lifecycle_check CHECK (
       (state = 'queued'    AND started_at IS NULL AND finished_at IS NULL
                            AND inference_item_id IS NULL AND outcome_code IS NULL)
    OR (state = 'running'   AND started_at IS NOT NULL AND finished_at IS NULL
                            AND outcome_code IS NULL)
    OR (state = 'completed' AND started_at IS NOT NULL AND finished_at IS NOT NULL
                            AND inference_item_id IS NOT NULL AND outcome_code IS NULL)
    OR (state IN ('no_data', 'failed') AND finished_at IS NOT NULL
                            AND outcome_code IS NOT NULL)
  ),
  CONSTRAINT ati_requests_selected_test_ids_check CHECK (
    CASE
      WHEN jsonb_typeof(selected_test_ids) = 'array'
      THEN jsonb_array_length(selected_test_ids) > 0
           AND NOT jsonb_path_exists(
             selected_test_ids,
             'strict $[*] ? (@.type() != "string" || @ == "")'
           )
      ELSE false
    END
  ),
  CONSTRAINT ati_requests_request_key_check CHECK (request_key ~ '^[A-Za-z0-9_-]{1,64}$'),
  CONSTRAINT ati_requests_academic_year_check CHECK (
    CASE
      WHEN academic_year ~ '^[0-9]{4}-[0-9]{4}$'
      THEN left(academic_year, 4)::int + 1 = right(academic_year, 4)::int
      ELSE false
    END
  ),
  CONSTRAINT ati_requests_notes_snapshot_check CHECK (jsonb_typeof(notes_snapshot) = 'array'),
  CONSTRAINT ati_requests_outcome_code_check CHECK (
    outcome_code IS NULL OR outcome_code ~ '^[a-z][a-z0-9_]{0,63}$'
  )
);

CREATE UNIQUE INDEX IF NOT EXISTS ati_requests_key_unique
  ON ai_test_insight_requests (request_key);

