-- Audit rows are append-only (23514 is check_violation). The body is copied
-- verbatim from db-service, because pg_dump compares it as text.
CREATE OR REPLACE FUNCTION ati_protect_session_note_audits()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  RAISE EXCEPTION 'AI Test Insight Session Note audits are append-only'
    USING ERRCODE = '23514';
END;
$$;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_trigger
    WHERE tgname = 'ati_session_note_audits_immutable'
      AND tgrelid = 'ai_test_insight_session_note_audits'::regclass
  ) THEN
    CREATE TRIGGER ati_session_note_audits_immutable
    BEFORE UPDATE OR DELETE ON ai_test_insight_session_note_audits
    FOR EACH ROW EXECUTE FUNCTION ati_protect_session_note_audits();
  END IF;
END $$;
