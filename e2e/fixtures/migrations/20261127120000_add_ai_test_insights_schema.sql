  -- Ticked tests, newest first.
  selected_test_ids jsonb NOT NULL,
  notes_snapshot jsonb NOT NULL DEFAULT '[]'::jsonb,
  state text NOT NULL DEFAULT 'queued',
  outcome_code text,
  inference_item_id bigint,
  -- The time the LMS's 20-minute stall rule counts from.
  requested_at timestamp(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
  started_at timestamp(0),
  finished_at timestamp(0),
  inserted_at timestamp(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
