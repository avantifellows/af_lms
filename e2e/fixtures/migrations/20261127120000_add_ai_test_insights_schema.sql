-- 20260616173000_allow_scoring_status_in_eval_run_benchmarks -----------------
-- Replaces the CHECK only while it still lacks 'scoring', so a second run
-- changes nothing.

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'am_eval_benchmarks_status_check'
      AND conrelid = 'acad_mentorship_eval_run_benchmarks'::regclass
      AND pg_get_constraintdef(oid) LIKE '%''scoring''%'
  ) THEN
    ALTER TABLE acad_mentorship_eval_run_benchmarks
      DROP CONSTRAINT IF EXISTS am_eval_benchmarks_status_check;
    ALTER TABLE acad_mentorship_eval_run_benchmarks
      ADD CONSTRAINT am_eval_benchmarks_status_check
      CHECK (scoring_status IN ('pending', 'scoring', 'scored', 'skipped', 'errored'));
  END IF;
END $$;

